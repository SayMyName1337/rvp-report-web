# -*- coding: utf-8 -*-
"""Страница инструкции.

Инструкция лежит шаблоном в репозитории, а не отдельным файлом PDF,
который кто-то поддерживает руками. Так она живёт вместе с кодом:
меняется страница — в том же коммите меняется её описание, и разойтись
они не могут. Печать даёт из неё PDF в один приём, если нужен именно
файл.
"""
from __future__ import annotations

from django.contrib.auth.mixins import LoginRequiredMixin
from django.views.generic import TemplateView


class GuideView(LoginRequiredMixin, TemplateView):
    """Руководство по работе с системой.

    Разделы показываются все и всем, а не по роли: человек может
    совмещать должности, и прятать от него половину инструкции —
    значит заставлять спрашивать. Кому что нужно, помечено в тексте.
    """

    template_name = "guide/index.html"
